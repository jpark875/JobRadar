def _alias_pattern(alias: str) -> str:
    return r"(?<![\w+#])" + re.escape(alias) + r"(?![\w+#]|\.\w)"


@lru_cache
def _compiled() -> list[tuple[str, re.Pattern]]:
    return [
        (canonical, re.compile("|".join(_alias_pattern(a) for a in sorted(aliases, key=len, reverse=True))))
        for canonical, aliases in SKILLS.items()
    ]


def extract_skills(text: str) -> list[str]:
    lowered = (text or "").lower()
    if not lowered:
        return []
    return [canonical for canonical, pattern in _compiled() if pattern.search(lowered)]


def normalize_skill(value: str) -> str:
    lowered = value.strip().lower()
    for canonical, aliases in SKILLS.items():
        if lowered == canonical or lowered in aliases:
            return canonical
    return lowered
